#3) Write a program to perform arithmetic relational and logical operations using Python operators.
print("Arithmaic Operation")
x=int(input("Enter Value of X:"))
y=int(input("Enter Value of Y:"))

print("X + Y =",x+y)

print("X - Y =",x-y)

print("X * Y =",x*y)

print("X / Y =",x/y)

print("X % Y =",x%y)

print("\nRelational Operation")

print("x > Y",x>y)

print("x < Y",x<y)

print("x != Y",x!=y)

print("x == Y",x==y)

print("x >= Y",x>=y)

print("x <= Y",x<=y)

print("\nLogical Operation")

print("AND :",(x>=y) and (x==y))

print("OR :",(x>y) or (x==y))

print("NOT :",not(x==y))
