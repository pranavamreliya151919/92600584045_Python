#2) Write a program to illustrate the use of different data types and type casting.

a = 10
b = 10.4
c = "Pranav"
d = True

print("Integer Value :",a)
print("Float Value :",b)
print("String Value :",c)
print("Boolean Value :",d)

print("AFTER TYPE CASTING")

v_int=float(a)
v_float=int(b)
v_str=str(a)

print("Integer To Float :",v_int,type(v_int))
print("Float To Integer :",v_float,type(v_float))
print("Integer To String :",v_str,type(v_str))
